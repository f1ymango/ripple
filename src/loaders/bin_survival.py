"""How many 5-minute bins each calibration threshold leaves (week 2, Data + Simulation).

GEH only uses bins with enough archive coverage and enough valid lane readings
(docs/02-data.md section 7), and the two thresholds are a team decision that
goes on the validation slide. This counts what each choice leaves -- before and
after the incident, and per detector -- and runs the coverage-versus-speed
check that section asks for before any filtering.

    python -m src.loaders.fetch bin-survival --start 2026-05-15T07:55 \\
        --end 2026-05-15T10:35 --split 2026-05-15T08:55
    -> results/data/bin-survival_20260515-0755_1035.md and .json
"""
from __future__ import annotations

import datetime as dt
import json
from collections import Counter
from pathlib import Path

from src.loaders import detectors
from src.loaders.corridor import DETECTOR_IDS

OUT_DIR = Path("results/data")
# (archive coverage %, valid lane readings %). The first pair is today's default.
THRESHOLDS = [(detectors.MIN_COVERAGE_PCT, detectors.MIN_LANE_COMPLETENESS_PCT),
              (30, 90), (20, 90), (40, 75), (20, 75)]
# The bias check compares two means; with fewer bins than this on either side
# there is nothing to compare, and the table says so instead of printing a gap.
MIN_COMPARE_BINS = 10


def _usable(binned: list[dict], coverage: int, lanes: int) -> int:
    return len(detectors.usable_for_calibration(binned, coverage, lanes))


def absent_detectors(binned: list[dict]) -> list[str]:
    """Detectors with no reading in any snapshot the archive delivered.

    The loader gives their slots coverage 0, the same as an archive gap, but
    the archive did deliver those snapshots: the detector was not in them.
    """
    seen = {b["detector_id"] for b in binned if b["periods_observed"]}
    return [d for d in DETECTOR_IDS if d not in seen and any(b["detector_id"] == d for b in binned)]


def survey(binned: list[dict], split: dt.datetime, archive_line: str = "") -> dict:
    """Everything the threshold decision needs, as plain numbers."""
    before = [b for b in binned if dt.datetime.fromisoformat(b["bin_start"]) < split]
    after = [b for b in binned if dt.datetime.fromisoformat(b["bin_start"]) >= split]
    # The bias check is about bins the archive sampled thinly, so slots with no
    # reading at all (nothing to take a speed from) stay out of it.
    observed = [b for b in binned if b["periods_observed"]]
    observed_before = [b for b in before if b["periods_observed"]]
    return {
        "archive": archive_line,
        "split": split.isoformat(),
        "slots": {"before": len(before), "after": len(after), "all": len(binned)},
        "coverage_pct_counts": dict(sorted(Counter(b["coverage_pct"] for b in binned).items())),
        "absent_detectors": absent_detectors(binned),
        "thresholds": [{"min_coverage_pct": c, "min_lane_completeness_pct": l,
                        "before": _usable(before, c, l), "after": _usable(after, c, l),
                        "all": _usable(binned, c, l)} for c, l in THRESHOLDS],
        "speed_bins": {"before": sum(b["speed_kmh"] != "" for b in before),
                       "after": sum(b["speed_kmh"] != "" for b in after)},
        "bias": {f"{part}_cov{c}": detectors.coverage_bias_check(rows, c)
                 for part, rows in (("before", observed_before), ("all", observed))
                 for c in sorted({c for c, _ in THRESHOLDS}, reverse=True)},
        "per_detector": [{"detector_id": d,
                          "before": _usable([b for b in before if b["detector_id"] == d], *THRESHOLDS[0]),
                          "after": _usable([b for b in after if b["detector_id"] == d], *THRESHOLDS[0]),
                          "slots": sum(b["detector_id"] == d for b in binned)}
                         for d in DETECTOR_IDS],
    }


def build(start: dt.datetime, end: dt.datetime, split: dt.datetime) -> dict:
    lines: list[str] = []
    rows = detectors.load_window(start, end, log=lines.append)
    binned = detectors.bin_window(rows, detectors.BIN_MINUTES, start=start, end=end)
    return {"start": start.isoformat(), "end": end.isoformat(),
            **survey(binned, split, lines[-1] if lines else "")}


def _cell(value) -> str:
    return "—" if value is None else str(value)


def _md(doc: dict, command: str) -> str:
    t, s = doc["thresholds"], doc["slots"]
    split = doc["split"][11:16]
    out = [f"# Usable calibration bins, {doc['start'][:10]} {doc['start'][11:16]}-{doc['end'][11:16]}",
           "", f"Generated by `{command}`. Regenerate rather than edit.", "",
           f"Archive: {doc['archive']}. 5-minute slots: {s['before']} before {split} "
           f"(pre-incident, for demand calibration) and {s['after']} from {split} "
           f"(incident and recovery), across {len(DETECTOR_IDS)} detectors.", "",
           "## Bins with a count usable for GEH", "",
           "| Archive coverage ≥ | Valid lane readings ≥ | Before | From | Whole window |",
           "|---|---|---|---|---|"]
    for r in t:
        out.append(f"| {r['min_coverage_pct']}% | {r['min_lane_completeness_pct']}% "
                   f"| {r['before']} of {s['before']} | {r['after']} of {s['after']} "
                   f"| {r['all']} of {s['all']} |")
    out += ["", f"Bins with a measured speed (speed survives low coverage): "
                f"{doc['speed_bins']['before']} before {split}, {doc['speed_bins']['after']} from it.",
            "", "## Coverage comes in steps", "",
            "A 5-minute bin holds whole archived minutes, so coverage comes in steps, and a "
            "threshold only matters where slots sit. How many slots sit at each value:", "",
            "| Coverage | Slots |", "|---|---|"]
    out += [f"| {k}% | {v} |" for k, v in doc["coverage_pct_counts"].items()]
    absent = doc["absent_detectors"]
    if absent:
        out += ["", f"The 0% slots include every slot of {', '.join(absent)}: no reading in any "
                    "snapshot the archive delivered, so the detector was missing from the feed. "
                    "That is not an archive gap, though the loader scores it the same way."]
    out += ["", "## Is filtering by coverage biased? (docs/02-data.md section 7)", "",
            "Mean speed of low- against high-coverage bins, over slots with at least one "
            "reading. A gap over 5 km/h would mean the filter selects for traffic conditions "
            "and has to be said on the validation slide.", "",
            "| Bins | Threshold | Low: bins, mean km/h | High: bins, mean km/h | Gap km/h |",
            "|---|---|---|---|---|"]
    for key, b in doc["bias"].items():
        part, cov = key.split("_cov")
        label = f"before {split}" if part == "before" else "whole window"
        few = min(b["low_coverage_bins"], b["high_coverage_bins"]) < MIN_COMPARE_BINS
        gap = f"too few bins below {cov}% to compare" if few else _cell(b["mean_speed_gap_kmh"])
        out.append(f"| {label} | {cov}% | {b['low_coverage_bins']}, "
                   f"{_cell(b['low_coverage_mean_speed'])} | {b['high_coverage_bins']}, "
                   f"{_cell(b['high_coverage_mean_speed'])} | {gap} |")
    c, l = THRESHOLDS[0]
    out += ["", f"## Per detector, at today's default ({c}% / {l}%)", "",
            f"| Detector | Usable before {split} | Usable from {split} | Slots |", "|---|---|---|---|"]
    out += [f"| {r['detector_id']} | {r['before']} | {r['after']} | {r['slots']} |"
            for r in doc["per_detector"]]
    return "\n".join(out) + "\n"


def write(doc: dict, command: str, out_dir: Path = OUT_DIR) -> tuple[Path, Path]:
    start, end = dt.datetime.fromisoformat(doc["start"]), dt.datetime.fromisoformat(doc["end"])
    stem = out_dir / f"bin-survival_{start:%Y%m%d-%H%M}_{end:%H%M}"
    out_dir.mkdir(parents=True, exist_ok=True)
    md, js = stem.with_suffix(".md"), stem.with_suffix(".json")
    md.write_text(_md(doc, command), encoding="utf-8", newline="\n")
    js.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    return md, js
