"""How fast drivers go when the road is clear, per detector (week 2, for the twin).

The twin's vehicle type caps every car at 60 km/h (maxSpeed 16.7 m/s in
src/twin/make_routes.py). This measures what the corridor's drivers actually do
in light traffic -- every valid lane reading with at least one vehicle and an
occupancy at or below LIGHT_OCCUPANCY_PCT -- on ordinary mornings, so the
twin's desired speeds can come from data rather than a default.

Each reading's speed is the lane's average over its vehicles in 30 seconds, so
readings are weighted by their vehicles; the spread between single cars inside
a reading is not in the feed.

    python -m src.loaders.fetch free-flow --day 2026-05-08 2026-04-24 --start 07:30 --end 11:00
    -> results/data/free-flow_20260508_20260424_0730-1100.md and .json
"""
from __future__ import annotations

import datetime as dt
import json
from collections import defaultdict
from pathlib import Path

from src.loaders import detectors
from src.loaders.common import HK
from src.loaders.corridor import DETECTOR_IDS

OUT_DIR = Path("results/data")
LIGHT_OCCUPANCY_PCT = 10    # a loop covered less than a tenth of the time: traffic is light
MIN_READINGS = 20           # fewer light-traffic readings than this is not a speed, it is an anecdote
TWIN_CAP_KMH = 60           # the twin's current cap, to count what it cannot reproduce


def light_readings(rows: list[dict]) -> dict[str, list[tuple[float, float]]]:
    """Per detector: (speed km/h, vehicles) for every lane reading in light traffic."""
    out: dict[str, list[tuple[float, float]]] = defaultdict(list)
    for r in rows:
        if (r["valid"] and r["volume"] and r["speed_kmh"] is not None
                and r["occupancy_pct"] is not None and r["occupancy_pct"] <= LIGHT_OCCUPANCY_PCT):
            out[r["detector_id"]].append((r["speed_kmh"], r["volume"]))
    return out


def percentile(pairs: list[tuple[float, float]], q: float) -> float:
    """The speed below which q% of the vehicles drove, each reading weighted by its vehicles."""
    ordered = sorted(pairs)
    total, running = sum(n for _, n in ordered), 0.0
    for speed, n in ordered:
        running += n
        if running >= q / 100 * total:
            return speed
    return ordered[-1][0]


def summary(pairs: list[tuple[float, float]]) -> dict:
    vehicles = sum(n for _, n in pairs)
    if len(pairs) < MIN_READINGS:
        return {"readings": len(pairs), "vehicles": round(vehicles), "enough": False}
    return {"readings": len(pairs), "vehicles": round(vehicles), "enough": True,
            "median_kmh": round(percentile(pairs, 50), 1),
            "p85_kmh": round(percentile(pairs, 85), 1),
            "above_cap_pct": round(sum(n for s, n in pairs if s > TWIN_CAP_KMH) / vehicles * 100)}


def build(days: list[dt.date], start: dt.time, end: dt.time) -> dict:
    """Light-traffic speeds pooled over the same clock window on each day."""
    pooled: dict[str, list] = defaultdict(list)
    archive = {}
    for day in days:
        lines: list[str] = []
        rows = detectors.load_window(dt.datetime.combine(day, start, HK),
                                     dt.datetime.combine(day, end, HK), log=lines.append)
        archive[day.isoformat()] = lines[-1] if lines else ""
        for d, pairs in light_readings(rows).items():
            pooled[d] += pairs
    return {"days": [d.isoformat() for d in days], "start": start.isoformat("minutes"),
            "end": end.isoformat("minutes"), "light_occupancy_pct": LIGHT_OCCUPANCY_PCT,
            "archive": archive, "detectors": {d: summary(pooled.get(d, [])) for d in DETECTOR_IDS}}


def _md(doc: dict, command: str) -> str:
    out = [f"# Free-flow speeds, {', '.join(doc['days'])}, {doc['start']}-{doc['end']}", "",
           f"Generated by `{command}`. Regenerate rather than edit.", "",
           "Speeds in light traffic: lane readings with at least one vehicle and occupancy at or "
           f"below {doc['light_occupancy_pct']}%, weighted by vehicles. *Above {TWIN_CAP_KMH}* is "
           f"the share of those vehicles faster than the twin's current {TWIN_CAP_KMH} km/h cap.", "",
           f"| Detector | Readings | Median km/h | 85th percentile km/h | Above {TWIN_CAP_KMH} |",
           "|---|---|---|---|---|"]
    for d, s in doc["detectors"].items():
        if s["enough"]:
            out.append(f"| {d} | {s['readings']} | {s['median_kmh']} | {s['p85_kmh']} "
                       f"| {s['above_cap_pct']}% |")
        else:
            out.append(f"| {d} | {s['readings']} | too few light-traffic readings | | |")
    out += ["", "Archive: " + "; ".join(f"{d}: {a}" for d, a in doc["archive"].items()), ""]
    return "\n".join(out)


def write(doc: dict, command: str, out_dir: Path = OUT_DIR) -> tuple[Path, Path]:
    days = "_".join(d.replace("-", "") for d in doc["days"])
    stem = out_dir / f"free-flow_{days}_{doc['start'].replace(':', '')}-{doc['end'].replace(':', '')}"
    out_dir.mkdir(parents=True, exist_ok=True)
    md, js = stem.with_suffix(".md"), stem.with_suffix(".json")
    md.write_text(_md(doc, command), encoding="utf-8", newline="\n")
    js.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    return md, js
