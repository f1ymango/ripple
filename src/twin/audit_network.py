"""Reproducible, offline OSM/TD mapping review. Does not run a simulation."""
import argparse
import csv
import json
import math
from pathlib import Path

import sumolib

from src.loaders.corridor import CHAIN_EASTBOUND, CHAIN_WESTBOUND
from src.twin.common import ROOT, load_json, resolve
from src.twin.network_sources import cached_lane_evidence, cached_osm_path, read_osm_ways, sha256


def relative(path):
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def read_mapping(path):
    """Retain lane-0's anchor position, matching the current mapper convention."""
    result = {}
    with path.open(encoding="utf-8-sig", newline="") as stream:
        for row in csv.DictReader(stream):
            if row["detector_id"] not in result or row["lane_id"].endswith("_0"):
                result[row["detector_id"]] = row
    return result


def chain_paths(net, mapping, registry):
    rows = []
    for sequence in (CHAIN_EASTBOUND, CHAIN_WESTBOUND):
        for a, b in zip(sequence, sequence[1:]):
            if a not in mapping or b not in mapping:
                rows.append({"from": a, "to": b, "status": "missing_mapping"})
                continue
            source, destination = mapping[a], mapping[b]
            path, cost = net.getShortestPath(
                net.getEdge(source["edge_id"]), net.getEdge(destination["edge_id"]),
                vClass="passenger", fromPos=float(source["position_m"]),
                toPos=float(destination["position_m"]))
            direct = math.hypot(float(registry[a]["easting"]) - float(registry[b]["easting"]),
                                float(registry[a]["northing"]) - float(registry[b]["northing"]))
            rows.append({
                "from": a, "to": b, "status": "reachable" if path else "unreachable",
                "direct_hk1980_m": round(direct, 3),
                "path_m": round(cost, 3) if path else None,
                "path_to_direct_ratio": round(cost / direct, 3) if path and direct else None,
                "edges": [edge.getID() for edge in path] if path else [],
            })
    return rows


def describe_mapping(net, mapping, registry, lane_evidence, osm_ways):
    rows = []
    for detector_id, mapped in sorted(mapping.items()):
        edge = net.getEdge(mapped["edge_id"])
        source = registry[detector_id]
        xy = net.convertLonLat2XY(float(source["longitude"]), float(source["latitude"]))
        projected_pos, lane_offset = edge.getLane(0).getClosestLanePosAndDist(xy)
        tags = osm_ways.get(edge.getID().split("#", 1)[0].lstrip("-"), {})
        evidence = lane_evidence["detectors"][detector_id]
        observed = evidence["lane_count"]
        rows.append({
            "detector_id": detector_id, "edge_id": edge.getID(),
            "position_m": float(mapped["position_m"]),
            "registry_road": source["road_en"], "osm_name": edge.getName(),
            "osm_name_tags": {k: v for k, v in tags.items()
                              if "name" in k and (k.endswith(":en") or v.isascii())},
            "osm_lanes_tag": tags.get("lanes"), "osm_turn_lanes": tags.get("turn:lanes"),
            "sumo_lanes": edge.getLaneNumber(), "td_lanes": observed,
            "lane_scope_status": "missing_or_variable_feed_scope" if observed is None else (
                "matches" if observed == edge.getLaneNumber() else "conflict"),
            "td_lane_sets": evidence["lane_sets"], "td_periods": evidence["observed_periods"],
            "lane_0_offset_m": round(lane_offset, 3),
            "projection_at_lane_endpoint": projected_pos <= 0 or projected_pos >= edge.getLength(),
        })
    return rows


def write_markdown(report, path):
    lines = ["# OSM network and detector audit", "",
             "Generated by `python -m src.twin.audit_network`; uses local sources only.",
             "This is a mapping audit, not traffic calibration or proof that teleports are fixed.", "",
             f"Network SHA-256: `{report['sources']['network']['sha256']}`", "",
             f"OSM SHA-256: `{report['sources']['osm']['sha256']}`", "",
             f"Feed window: {' to '.join(report['lane_evidence']['window'])}.",
             f"Contributing cached snapshots: {len(report['lane_evidence']['sources'])}.", "",
             "## Detector lane scope", "",
             "SUMO counts include every modelled lane. Differences remain visible; no lanes",
             "or source observations are removed to force agreement. Endpoint projections",
             "and lane offsets identify junctions where placement still needs inspection.", "",
             "| Detector | Edge | Position m | TD lanes | SUMO lanes | Scope | Lane-0 offset m | Endpoint |",
             "|---|---|---:|---:|---:|---|---:|---|"]
    for row in report["detectors"]:
        lines.append(f"| {row['detector_id']} | `{row['edge_id']}` | {row['position_m']:.2f} | "
                     f"{row['td_lanes']} | {row['sumo_lanes']} | {row['lane_scope_status']} | "
                     f"{row['lane_0_offset_m']:.2f} | {row['projection_at_lane_endpoint']} |")
    lines += ["", "## Directed main-corridor connectivity", "",
              "Distances use detector positions and include internal junction connectors.",
              "Direct distances use the registry's HK1980 coordinates. A ratio is a review",
              "signal; it does not by itself prove an OSM topology error. Projected positions",
              "may produce ratios below one because source coordinates lie off modelled lanes.", "",
              "| From | To | Before m | Current m | Direct m | Current ratio | Status |",
              "|---|---|---:|---:|---:|---:|---|"]
    before = {(r['from'], r['to']): r for r in report.get('before_paths', [])}
    for row in report['paths']:
        previous = before.get((row['from'], row['to']), {}).get('path_m', '-')
        lines.append(f"| {row['from']} | {row['to']} | {previous} | {row.get('path_m')} | "
                     f"{row.get('direct_hk1980_m')} | {row.get('path_to_direct_ratio')} | {row['status']} |")
    lines += ["", "The companion JSON records file hashes, original OSM name/turn tags,",
              "observed lane sets and each route's edge sequence. Counts and speeds are",
              "never rewritten by this audit.", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', required=True)
    parser.add_argument('--detectors', required=True)
    parser.add_argument('--raw-cache', default='data/raw/detectors')
    parser.add_argument('--before-mapping')
    parser.add_argument('--out', default='results/twin/osm-network-audit.json')
    args = parser.parse_args()
    cfg, observations = load_json(resolve(args.config)), load_json(resolve(args.detectors))
    registry_path = resolve('data/detectors.csv')
    with registry_path.open(encoding='utf-8-sig', newline='') as stream:
        registry = {r['detector_id']: r for r in csv.DictReader(stream)}
    paths = {'config': resolve(args.config), 'network': resolve(cfg['network']), 'osm': cached_osm_path(cfg),
             'registry': registry_path, 'observations': resolve(args.detectors),
             'mapping': resolve(cfg['detector_additional']).with_suffix('.csv')}
    if cfg.get('detector_overrides'):
        paths['overrides'] = resolve(cfg['detector_overrides'])
    if args.before_mapping:
        paths['before_mapping'] = resolve(args.before_mapping)
    sources = {key: {'path': relative(path), 'sha256': sha256(path)} for key, path in paths.items()}
    net = sumolib.net.readNet(str(paths['network']), withInternal=True)
    lane_evidence = cached_lane_evidence(resolve(args.raw_cache), observations['source']['window'], registry)
    for group in ('sources', 'skipped'):
        for row in lane_evidence[group]:
            row['path'] = relative(Path(row['path']))
    mapping = read_mapping(paths['mapping'])
    report = {'sources': sources, 'lane_evidence': lane_evidence,
              'detectors': describe_mapping(net, mapping, registry, lane_evidence, read_osm_ways(paths['osm'])),
              'paths': chain_paths(net, mapping, registry)}
    if args.before_mapping:
        report['before_paths'] = chain_paths(net, read_mapping(paths['before_mapping']), registry)
    out = resolve(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2, ensure_ascii=False, allow_nan=False) + '\n', encoding='utf-8')
    write_markdown(report, out.with_suffix('.md'))
    print(f"Audited {len(report['detectors'])} detectors, {len(report['paths'])} directed pairs; "
          f"{sum(r['lane_scope_status'] != 'matches' for r in report['detectors'])} unresolved lane scopes.\n{out}")


if __name__ == '__main__':
    main()
